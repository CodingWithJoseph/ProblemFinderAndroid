def number(value):
    return f"{float(value):g}"


def path_data(element):
    tag = element.tag.rsplit("}", 1)[-1]
    a = element.attrib
    if "transform" in a:
        raise ValueError("Transforms require explicit conversion")
    if tag == "path":
        return a["d"]
    if tag == "line":
        return f'M {a["x1"]} {a["y1"]} L {a["x2"]} {a["y2"]}'
    if tag in ("polyline", "polygon"):
        coords = re.findall(r"[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?", a["points"])
        if len(coords) < 4 or len(coords) % 2:
            raise ValueError("Invalid SVG points")
        result = "M " + " ".join(coords[:2]) + " L " + " ".join(coords[2:])
        return result + (" Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        x, y = float(a["cx"]), float(a["cy"])
        rx = float(a["r"] if tag == "circle" else a["rx"])
        ry = float(a["r"] if tag == "circle" else a["ry"])
        return f"M {number(x-rx)} {number(y)} a {number(rx)} {number(ry)} 0 1 0 {number(2*rx)} 0 a {number(rx)} {number(ry)} 0 1 0 {number(-2*rx)} 0"
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = min(float(a.get("rx", a.get("ry", 0))), w / 2)
        ry = min(float(a.get("ry", a.get("rx", 0))), h / 2)
        if not rx or not ry:
            return f"M {number(x)} {number(y)} h {number(w)} v {number(h)} h {number(-w)} Z"
        return (
            f"M {number(x+rx)} {number(y)} H {number(x+w-rx)} "
            f"A {number(rx)} {number(ry)} 0 0 1 {number(x+w)} {number(y+ry)} V {number(y+h-ry)} "
            f"A {number(rx)} {number(ry)} 0 0 1 {number(x+w-rx)} {number(y+h)} H {number(x+rx)} "
            f"A {number(rx)} {number(ry)} 0 0 1 {number(x)} {number(y+h-ry)} V {number(y+ry)} "
            f"A {number(rx)} {number(ry)} 0 0 1 {number(x+rx)} {number(y)} Z"
        )
    raise ValueError(f"Unsupported SVG element: {tag}")


def android_vector(svg, name, version, mirror=False):
    root = ET.fromstring(svg)
    if root.attrib.get("viewBox") != "0 0 24 24" or root.attrib.get("fill") != "none":
        raise ValueError("Unexpected Lucide viewport or fill")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Lucide {name}, lucide-static {version}. Generated by scripts/sync_lucide_icons.py.",
        "     License: res/raw/lucide_license.txt -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24"' +
        (' android:autoMirrored="true"' if mirror else '') + '>',
    ]
    for element in root:
        if element.attrib.get("fill", "none") != "none" or element.attrib.get("stroke", "currentColor") != "currentColor":
            raise ValueError("Unexpected per-element paint")
        lines.extend([
            '    <path android:fillColor="@android:color/transparent"',
            '        android:strokeColor="#FF000000"',
            f'        android:strokeWidth="{element.attrib.get("stroke-width", root.attrib["stroke-width"])}"',
            '        android:strokeLineCap="round" android:strokeLineJoin="round"',
            f'        android:pathData="{escape(path_data(element), {chr(34): "&quot;"})}" />',
        ])
    return "\n".join(lines + ["</vector>", ""])


def main():
    version = tomllib.loads((ROOT / "gradle/libs.versions.toml").read_text())["versions"]["lucide-icons"]
    with urllib.request.urlopen(f"https://registry.npmjs.org/lucide-static/{version}", timeout=30) as response:
        metadata = json.load(response)
    with urllib.request.urlopen(metadata["dist"]["tarball"], timeout=30) as response:
        data = response.read()
    integrity = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if integrity != metadata["dist"]["integrity"]:
        raise ValueError("Package integrity check failed")
    # Prepare everything before writing, so unsupported geometry cannot leave a partial import.
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        vectors = {
            resource: android_vector(
                archive.extractfile(f"package/icons/{name}.svg").read(), name, version,
                mirror=resource in ("icon_arrow_forward", "icon_arrow_back", "icon_sign_out"),
            ) for resource, name in ICONS.items()
        }
        license_text = archive.extractfile("package/LICENSE").read().decode()
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "raw").mkdir(parents=True, exist_ok=True)
    for resource, vector in vectors.items():
        (RES / "drawable" / f"{resource}.xml").write_text(vector, encoding="utf-8")
    (RES / "raw/lucide_license.txt").write_text(
        f"Lucide icons, lucide-static {version}\nhttps://lucide.dev/license\n\n" + license_text,
        encoding="utf-8",
    )
    print(f"Imported {len(vectors)} Lucide {version} icons and their license into core:designsystem.")


if __name__ == "__main__":
    main()
